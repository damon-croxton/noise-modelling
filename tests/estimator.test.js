/* Reconciliation with the TfNSW Construction Noise Estimator spreadsheet.
   tests/golden/estimator-cases.json is generated by tools/estimator_golden.py
   (the spreadsheet recalculated in LibreOffice). */
'use strict';
const golden = require('./golden/estimator-cases.json');
const PERIODS = ['std', 'p1day', 'p1eve', 'p2eve', 'p2night'];

/* Everything the app computes for one golden case, with the given rule set. */
async function ours(page, ruleSet) {
  return page.evaluate(([cases, rs, periods]) => {
    const T = window.__noise._t;
    T.setRuleSet(rs);
    return cases.map(c => {
      const r = c.result, season = c.season === 'May to Sep' ? 'cool' : 'warm';
      let swl = c.swl;
      if (c.kind === 'plant') swl = T.estimatorCombine(c.plantRows.map(p => ({ G: T.estimatorRowLevel(p.lw, p.qty, p.intermittent, p.screened), qty: p.qty }))).swl;
      const I7 = T.estimatorLevel(swl, c.dist, c.screening, c.soft, season, false), J7 = T.estimatorLevel(swl, c.dist, c.screening, c.soft, season, true);
      const nca = { cat: c.area, rbl: { day: c.rbl.day ?? null, evening: c.rbl.evening ?? null, night: c.rbl.night ?? null } };
      const out = { swl, I7, J7, nml: {}, exc: {}, measures: {} };
      for (const p of periods) {
        const nml = T.nmlFor('residential', nca, p).nml, x = T.classify(p === 'p2night' ? J7 : I7, nml, p, 'residential');
        out.nml[p] = nml; out.exc[p] = x.exc <= 0 ? 'Compliant' : x.exc; out.measures[p] = x.measures.slice().sort();
      }
      const sl = T.sleepCheck(J7, nca, 'residential', 'p2night');
      out.lmax = sl.lmax; out.sleepScreen = sl.screen; out.sleepOver = sl.overScreen;
      return out;
    });
  }, [golden.cases, ruleSet, PERIODS]);
}

module.exports = [
  {
    name: `plant combination, levels, NMLs, exceedances and measures match the spreadsheet (${golden.cases.length} cases)`,
    async run({ page, assert }) {
      const res = await ours(page, 'estimator'), bad = [];
      golden.cases.forEach((c, i) => {
        const g = c.result, o = res[i], near = (a, b, t) => Math.abs(a - b) <= t;
        if (!near(o.swl, g.swl, 1e-6)) bad.push(`${c.name}: SWL ${o.swl} vs ${g.swl}`);
        if (!near(o.I7, g.I7, 1e-6) || !near(o.J7, g.J7, 1e-6)) bad.push(`${c.name}: levels ${o.I7}/${o.J7} vs ${g.I7}/${g.J7}`);
        if (!near(o.lmax, g.K7, 1e-6)) bad.push(`${c.name}: LAmax ${o.lmax} vs ${g.K7}`);
        if (o.sleepScreen !== g.sleepScreen) bad.push(`${c.name}: sleep screening ${o.sleepScreen} vs ${g.sleepScreen}`);
        if ((o.sleepOver ? 'Yes' : 'No') !== g.sleepExceeded) bad.push(`${c.name}: sleep exceeded ${o.sleepOver} vs ${g.sleepExceeded}`);
        for (const p of PERIODS) {
          if (o.nml[p] !== g.nml[p]) bad.push(`${c.name} ${p}: NML ${o.nml[p]} vs ${g.nml[p]}`);
          if (o.exc[p] !== g.exceedance[p]) bad.push(`${c.name} ${p}: exceedance ${o.exc[p]} vs ${g.exceedance[p]}`);
          if (o.measures[p].join() !== g.measures[p].join()) bad.push(`${c.name} ${p}: measures ${o.measures[p]} vs ${g.measures[p]}`);
        }
      });
      assert.deepStrictEqual(bad, []);
    }
  },
  {
    name: 'CNVG-PTI v4.6 Table 9 vs the spreadsheet: differences reported',
    async run({ page, assert }) {
      const res = await ours(page, 'cnvg'), diffs = {};
      let n = 0;
      golden.cases.forEach((c, i) => PERIODS.forEach(p => {
        n++;
        const a = res[i].measures[p].join(' '), b = c.result.measures[p].join(' ');
        if (a !== b) { const k = `${p}: guideline [${a}] vs estimator [${b}]`; diffs[k] = (diffs[k] || 0) + 1; }
      }));
      const total = Object.values(diffs).reduce((a, b) => a + b, 0);
      console.log(`      ${total} of ${n} case-periods give different measures under the guideline's Table 9:`);
      for (const [k, v] of Object.entries(diffs).sort()) console.log(`        ${v} × ${k}`);
      assert.ok(total > 0, 'expected the documented differences');
    }
  }
];
